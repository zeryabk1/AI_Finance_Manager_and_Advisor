"""
accounts/backends.py
----------------------
Allows login with EITHER username OR email + password.

Company Owners still have a username (chosen at registration).
Employees/Accountants created by an Owner (see companies/views.py:
manage_staff) are given username == email automatically, so in
practice they log in with their email — but this backend supports
both cases uniformly.
"""
from django.contrib.auth import get_user_model
from django.contrib.auth.backends import ModelBackend
from django.db.models import Q

User = get_user_model()


class EmailOrUsernameBackend(ModelBackend):
    def authenticate(self, request, username=None, password=None, **kwargs):
        if username is None:
            username = kwargs.get(User.USERNAME_FIELD)
        if username is None or password is None:
            return None
        try:
            user = User.objects.get(Q(username__iexact=username) | Q(email__iexact=username))
        except User.DoesNotExist:
            return None
        except User.MultipleObjectsReturned:
            # Prefer an exact username match if both exist
            user = User.objects.filter(username__iexact=username).first()
            if user is None:
                return None

        if user.check_password(password) and self.user_can_authenticate(user):
            return user
        return None
